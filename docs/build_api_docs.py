"""Build a static API reference for ``robustband`` using only the standard library.

Usage
-----
    python docs/build_api_docs.py [output_dir]     # default: docs/api

What it does
------------
Writes one HTML page per module (``pydoc`` for the package and each submodule) plus an
``index.html`` that links them.  No third-party tooling (no Sphinx, no pdoc) and no
network access -- consistent with the project's zero-dependency stance, and usable on an
air-gapped machine.

Exit codes
----------
0  pages written
2  the package could not be imported (the docs would be empty)
"""
import importlib
from html import escape
import pathlib
import pydoc
import re
import sys

MODULES = [
    "robustband",
    "robustband.core",
    "robustband.claim",
    "robustband.parsers",
    "robustband.metrics",
    "robustband.aggregate",
    "robustband.certificate",
    "robustband.rational",
    "robustband.adapter",
    "robustband.evalscope",
    "robustband.review",
    "robustband.review_dual",
    "robustband.review_search",
    "robustband.compiled",
    "robustband.workflow",
    "robustband.audit_engine",
    "robustband.input_utils",
    "robustband.convert",
    "robustband.storage",
    "robustband.domains",
    "robustband.segmentation",
    "robustband.scores",
    "robustband.decision",
    "robustband.decision_report",
    "robustband.matrix",
    "robustband.matrix_report",
    "robustband.report",
    "robustband.report_style",
    "robustband.cli",
    "robustband.local_ui",
]

INDEX = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>robustband - API reference</title>
<style>
 body {{ font-family: -apple-system, Segoe UI, Roboto, Helvetica, Arial, sans-serif;
        margin: 2rem auto; max-width: 46rem; line-height: 1.5; color: #222; }}
 h1 {{ margin-bottom: .2rem; }}
 .ver {{ color: #666; margin-top: 0; }}
 li {{ margin: .25rem 0; }}
 code {{ background: #f4f4f4; padding: .1rem .3rem; border-radius: 3px; }}
 footer {{ margin-top: 2.5rem; color: #666; font-size: .9rem; }}
</style>
</head>
<body>
<h1>robustband &mdash; API reference</h1>
<p class="ver">version {version} &middot; generated from the source tree with the Python
standard library (<code>pydoc</code>)</p>
<p>{summary}</p>
<ul>
{items}
</ul>
<footer>Generated by <code>docs/build_api_docs.py</code>; rebuild with
<code>python docs/build_api_docs.py</code>. MIT licensed.</footer>
</body>
</html>
"""


def main(argv):
    root = pathlib.Path(__file__).resolve().parent.parent
    out = pathlib.Path(argv[1]).resolve() if len(argv) > 1 else root / "docs" / "api"
    out.mkdir(parents=True, exist_ok=True)
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))

    try:
        pkg = importlib.import_module("robustband")
    except Exception as exc:  # pragma: no cover - environment problem, not a code path
        print(f"[api-docs] cannot import robustband: {exc}", file=sys.stderr)
        return 2

    written = []
    for name in MODULES:
        try:
            mod = importlib.import_module(name)
        except ImportError as exc:
            print(f"[api-docs] skip {name}: {exc}", file=sys.stderr)
            continue
        page = out / f"{name}.html"
        document = pydoc.html.document(mod, name)
        relative = pathlib.Path(mod.__file__).resolve().relative_to(root).as_posix()
        source_url = "https://github.com/wicalgambles-jpg/robustband-public/blob/main/" + relative
        document = re.sub(r'<a href="file:[^"]*">.*?</a>',
                          '<a href="'+source_url+'">'+escape(relative)+'</a>', document)
        page.write_text(document, encoding="utf-8")
        written.append((name, page.name, page.stat().st_size))

    items = "\n".join(
        f'  <li><a href="{fname}"><code>{name}</code></a></li>' for name, fname, _ in written
    )
    (out / "index.html").write_text(
        INDEX.format(
            version=getattr(pkg, "__version__", "?"),
            summary=(pkg.__doc__ or "").strip().splitlines()[0],
            items=items,
        ),
        encoding="utf-8",
    )

    for name, fname, size in written:
        print(f"[api-docs] {name:24s} -> {fname} ({size} bytes)")
    print(f"[api-docs] index -> {(out / 'index.html')}  ({len(written)} module pages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
